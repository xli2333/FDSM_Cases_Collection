// Get random keywords from a discipline
export function getRandomKeywordsFromDiscipline(disciplineId: number, count: number): string[] {
  const discipline = disciplines.find(d => d.id === disciplineId)
  if (!discipline) return []

  const shuffled = [...discipline.keywords].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, Math.min(count, shuffled.length))
}

// Get discipline by index (for rotation)
export function getDisciplineByIndex(index: number): DisciplineData {
  return disciplines[index % disciplines.length]
}
